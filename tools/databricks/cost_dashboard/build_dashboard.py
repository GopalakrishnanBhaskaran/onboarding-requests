def build() -> dict[Path, str]:
    GENERATED_SQL["16_recommendations"] = recommendations_sql()
    GENERATED_SQL["17_top_identities"] = top_identities_sql()
    dash = {"datasets": [dataset_json(s, d) for s, d in DATASETS], "pages": pages(),
            "uiSettings": {"theme": {"widgetHeaderAlignment": "ALIGNMENT_UNSPECIFIED"}}}
    return {
        SQL / "16_recommendations.sql": GENERATED_SQL["16_recommendations"],
        SQL / "17_top_identities.sql": GENERATED_SQL["17_top_identities"],
        OUT: json.dumps(dash, indent=2) + "\n",
    }


def main(argv: list[str]) -> int:
    generated = build()
    if "--check" in argv:
        stale = [p.name for p, t in generated.items() if not p.exists() or p.read_text() != t]
        if stale:
            print("out of date (run build_dashboard.py):", ", ".join(stale))
            return 1
        print("generated files are up to date")
        return 0
    for path, text_ in generated.items():
        path.write_text(text_)
