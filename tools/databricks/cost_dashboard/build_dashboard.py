"""Build the PEST cost-monitoring AI/BI dashboard from the SQL files.

Outputs (both committed, both regenerated by this script):
  sql/16_recommendations.sql      union of the waste datasets 10-15 (same 13 columns)
  sql/17_top_identities.sql       dataset 08 limited to the top 20 (for the bar chart)
  cost_dashboard.lvdash.json      the dashboard file (import it, or deploy with ../cost_dashboard.sh)

The widget specs copy the structure of the Databricks dashboard that Learn links
from "Monitor job costs & performance with system tables" (LakeFlow System Tables
Dashboard v0.1.lvdash.json): table v1, bar/line v3, counter v2, filter-date-picker
and filter-multi-select v2, DATE parameters with defaults now-30d/d and now/d.

Usage:
  python3 build_dashboard.py            # write the outputs
  python3 build_dashboard.py --check    # exit 1 if an output is out of date
"""
