def sql_text(stem: str) -> str:
    """Dataset SQL: the freshly generated text for generated files, else the file."""
    return GENERATED_SQL.get(stem) or (SQL / f"{stem}.sql").read_text()


def params_used(sql: str) -> list[str]:
    return [p for p in PARAM_DEFAULTS if re.search(rf":{p}\b", sql)]


def dataset_json(stem: str, display: str) -> dict:
    sql = sql_text(stem)
    ds = {"name": DS[stem], "displayName": display, "queryLines": sql.splitlines(keepends=True)}
    used = params_used(sql)
    if used:
        ds["parameters"] = [{
            "displayName": p, "keyword": p, "dataType": "DATE",
            "defaultSelection": {"values": {"dataType": "DATE", "values": [{"value": PARAM_DEFAULTS[p]}]}},
        } for p in used]
    return ds


# ---------- widgets ----------
def text(page: str, key: str, lines: list[str], x, y, w, h) -> dict:
    return {"widget": {"name": hid(page, key), "multilineTextboxSpec": {"lines": lines}},
            "position": {"x": x, "y": y, "width": w, "height": h}}


def field(name: str, expression: str | None = None) -> dict:
    return {"name": name, "expression": expression or f"`{name}`"}


def counter(page, key, stem, column, title, x, y, w=1, h=2, agg: str | None = None) -> dict:
    fname = f"{agg.lower()}({column})" if agg else column
    expr = f"{agg}(`{column}`)" if agg else None
    return {"widget": {
        "name": hid(page, key),
        "queries": [{"name": "main_query", "query": {
            "datasetName": DS[stem], "fields": [field(fname, expr)], "disaggregated": agg is None}}],
        "spec": {"version": 2, "widgetType": "counter",
                 "encodings": {"value": {"fieldName": fname, "displayName": title}},
                 "frame": {"showTitle": True, "title": title}}},
        "position": {"x": x, "y": y, "width": w, "height": h}}


def chart(page, key, kind, stem, x_col, y_col, title, x, y, w, h, color: str | None = None,
          x_temporal=False, agg="SUM") -> dict:
    y_name = f"{agg.lower()}({y_col})"
    fields = [field(x_col), field(y_name, f"{agg}(`{y_col}`)")]
    enc = {
        "x": {"fieldName": x_col, "scale": {"type": "temporal" if x_temporal else "categorical"},
              "displayName": x_col},
        "y": {"fieldName": y_name, "scale": {"type": "quantitative"}, "displayName": y_col,
              "format": {"type": "number-plain", "abbreviation": "compact",
                         "decimalPlaces": {"type": "max", "places": 2}}},
    }
    if color:
        fields.append(field(color))
        enc["color"] = {"fieldName": color, "scale": {"type": "categorical"}, "displayName": color}
    spec = {"version": 3, "widgetType": kind, "encodings": enc, "frame": {"showTitle": True, "title": title}}
    if kind == "bar" and color:
        spec["mark"] = {"layout": "stack"}
    return {"widget": {"name": hid(page, key),
                       "queries": [{"name": "main_query", "query": {
                           "datasetName": DS[stem], "fields": fields, "disaggregated": False}}],
                       "spec": spec},
            "position": {"x": x, "y": y, "width": w, "height": h}}


TYPE_SPECS = {
    "string": {"type": "string", "displayAs": "string", "alignContent": "left"},
    "float": {"type": "float", "displayAs": "number", "numberFormat": "0.00", "alignContent": "right"},
    "integer": {"type": "integer", "displayAs": "number", "numberFormat": "0", "alignContent": "right"},
    "date": {"type": "datetime", "displayAs": "datetime", "dateTimeFormat": "YYYY-MM-DD", "alignContent": "right"},
}


def table(page, key, stem, columns: list[tuple[str, str, str]], title, x, y, w, h) -> dict:
    cols = []
    for order, (name, kind, label) in enumerate(columns):
        c = {"fieldName": name}
        t = dict(TYPE_SPECS[kind])
        align = t.pop("alignContent")
        c.update({k: v for k, v in t.items() if k in ("numberFormat", "dateTimeFormat")})
        c.update({
            "booleanValues": ["false", "true"], "imageUrlTemplate": "{{ @ }}", "imageTitleTemplate": "{{ @ }}",
            "imageWidth": "", "imageHeight": "", "linkUrlTemplate": "{{ @ }}", "linkTextTemplate": "{{ @ }}",
            "linkTitleTemplate": "{{ @ }}", "linkOpenInNewTab": True,
            "type": t["type"], "displayAs": t["displayAs"], "visible": True, "order": order, "title": label,
            "allowSearch": kind == "string", "alignContent": align, "allowHTML": False,
            "highlightLinks": False, "useMonospaceFont": False, "preserveWhitespace": False,
            "displayName": name,
        })
        cols.append(c)
    return {"widget": {
        "name": hid(page, key),
        "queries": [{"name": "main_query", "query": {
            "datasetName": DS[stem], "fields": [field(n) for n, _, _ in columns], "disaggregated": True}}],
        "spec": {"version": 1, "widgetType": "table", "encodings": {"columns": cols},
                 "invisibleColumns": [], "allowHTMLByDefault": False, "itemsPerPage": 25,
                 "paginationSize": "default", "condensed": True, "withRowNumber": False,
                 "frame": {"showTitle": True, "title": title}}},
        "position": {"x": x, "y": y, "width": w, "height": h}}


def date_filter(page, param, title, stems, x, y, w=1, h=1) -> dict:
    queries, fields = [], []
    for stem in stems:
        if param not in params_used(sql_text(stem)):
            continue
        qn = f"parameter_{DS[stem]}_{param}"
        queries.append({"name": qn, "query": {"datasetName": DS[stem],
                                              "parameters": [{"name": param, "keyword": param}],
                                              "disaggregated": False}})
        fields.append({"parameterName": param, "queryName": qn})
    return {"widget": {"name": hid(page, "filter", param), "queries": queries,
                       "spec": {"version": 2, "widgetType": "filter-date-picker",
                                "encodings": {"fields": fields}, "frame": {"showTitle": True, "title": title}}},
            "position": {"x": x, "y": y, "width": w, "height": h}}


def field_filter(page, column, title, stems, x, y, w=2, h=1) -> dict:
    queries, fields = [], []
    for stem in stems:
        qn = f"filter_{DS[stem]}_{column}"
        queries.append({"name": qn, "query": {"datasetName": DS[stem], "fields": [
            field(column), field(f"{column}_associativity", "COUNT_IF(`associative_filter_predicate_group`)")],
            "disaggregated": False}})
        fields.append({"fieldName": column, "displayName": column, "queryName": qn})
    return {"widget": {"name": hid(page, "filter", column), "queries": queries,
                       "spec": {"version": 2, "widgetType": "filter-multi-select",
                                "encodings": {"fields": fields}, "frame": {"showTitle": True, "title": title}}},
            "position": {"x": x, "y": y, "width": w, "height": h}}


def date_filters(page, stems, y) -> list[dict]:
    return [date_filter(page, "start_date", "Start date (UTC)", stems, 0, y),
            date_filter(page, "end_date", "End date (UTC)", stems, 1, y)]


